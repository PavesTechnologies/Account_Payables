    def update_bank(
        self,
        vendor_id: int,
        vendor_bank_id: int,
        data: VendorBankUpdateRequest,
        user_id: str,
    ) -> VendorBank:

        self._require_vendor(vendor_id)
        bank = self.vendor_dao.get_vendor_bank_by_id(vendor_id, vendor_bank_id)
        if bank is None:
            raise ValueError("Bank not found")

        before = self._bank_snapshot(bank)

        if data.bank_name is not None:
            if not data.bank_name.strip():
                raise ValueError("bank_name is required for a vendor bank account")
            bank.bank_name = data.bank_name
        if data.account_holder_name is not None:
            bank.account_holder_name = validate_bank_account_holder_name(
                data.account_holder_name
            )
        if data.account_number is not None:
            bank.account_number = validate_bank_account_number(data.account_number)
        if data.iban is not None:
            bank.iban = data.iban
        if data.swift_code is not None:
            bank.swift_code = data.swift_code
        if data.routing_number is not None:
            bank.routing_number = data.routing_number
        if data.ifsc_code is not None:
            bank.ifsc_code = validate_ifsc(data.ifsc_code)

        if data.account_number is not None or data.iban is not None:
            if not bank.account_number and not bank.iban:
                raise ValueError(
                    "At least one of account_number or iban is required for a vendor bank account"
                )
            if self.vendor_dao.account_identifier_exists_for_vendor(
                vendor_id, bank.account_number, bank.iban, exclude_bank_id=vendor_bank_id
            ):
                raise ValueError("This account_number/iban already exists for this vendor")
            if self._bank_duplicate_across_vendors_enabled() and self.vendor_dao.account_identifier_exists_across_vendors(
                bank.account_number, bank.iban, exclude_vendor_id=vendor_id
            ):
                raise ValueError("This account_number/iban already exists for another vendor")

        if data.is_primary is True and not bank.is_primary:
            existing_primary = self.vendor_dao.get_active_primary_bank(vendor_id)
            if existing_primary is not None:
                existing_primary.effective_to = datetime.date.today()
                existing_primary.is_primary = False
            bank.is_primary = True
        elif data.is_primary is False:
            bank.is_primary = False

        after = self._bank_snapshot(bank)
        changed = {key: value for key, value in after.items() if before.get(key) != value}

        if changed:
            self._write_audit(
                table_name="vendor_bank",
                record_id=bank.vendor_bank_id,
                action="UPDATE",
                changed_by=user_id,
                old_values={key: before.get(key) for key in changed},
                new_values=changed,
            )

        self.db.commit()
        self.db.refresh(bank)

        return bank

