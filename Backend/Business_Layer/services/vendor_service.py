    @staticmethod
    def _validate_bank_identifiers(
        account_number: Optional[str],
        iban: Optional[str],
        ifsc_code: Optional[str],
    ) -> tuple:
        if not account_number and not iban:
            raise ValueError(
                "At least one of account_number or iban is required for a vendor bank account"
            )

        validated_account_number = (
            validate_bank_account_number(account_number) if account_number else None
        )
        validated_ifsc_code = validate_ifsc(ifsc_code) if ifsc_code else None

        return validated_account_number, validated_ifsc_code

    def _bank_duplicate_across_vendors_enabled(self) -> bool:
        config_value = self.vendor_dao.get_config_value(
            BANK_DUPLICATE_ACROSS_VENDORS_CONFIG_KEY
        )
        return (config_value or "").strip().lower() == "true"

    def _check_bank_duplicates(
        self,
        vendor_id: int,
        account_number: Optional[str],
        iban: Optional[str],
    ) -> None:
        if self.vendor_dao.account_identifier_exists_for_vendor(vendor_id, account_number, iban):
            raise ValueError("This account_number/iban already exists for this vendor")

        if self._bank_duplicate_across_vendors_enabled() and self.vendor_dao.account_identifier_exists_across_vendors(
            account_number, iban, exclude_vendor_id=vendor_id
        ):
            raise ValueError("This account_number/iban already exists for another vendor")

